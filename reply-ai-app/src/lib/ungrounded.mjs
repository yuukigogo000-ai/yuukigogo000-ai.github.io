// 入力(会話・プロフィール・文体サンプル)に出ていない固有名詞の検出。
//
// 目的: AIが「行ったことのある体」で店名・施設名・地名を発明すると、送った本人が
// 次のターンで答えられなくなる(2026-09-01 追従テストで実測: 例「最近アクアマリンを
// 行ってきたんですけど」= 入力に無い施設名+架空の体験談)。
//
// これは「警告」用の検出器で、ブロッカーではない。スクショ内の文字は照合できないため、
// スクショに出ていた名前が誤って挙がることがある(UI側の文言でその旨を伝える)。
//
// このファイルは reply-ai-app(本番UI)と pricing_eval(評価器)の両方から import される
// 単一実装。片方だけ直すと乖離するので、変更時は pricing_eval のテストを必ず回すこと。

// REPLY_SYSTEM の例文に出てくる実在固有名詞。入力に無ければ長さに関係なく必ず挙げる
// (モデルが例文を本人の体験として流用する事故が3モデルすべてで実測された)。
export const PROMPT_EXAMPLE_NAMES = ['高尾山', '代官山'];

// カタカナ4文字以上のうち、固有名詞でない日常語(誤検知を減らすための許可リスト)。
