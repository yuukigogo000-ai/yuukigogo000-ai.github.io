// 施設・店を示す接尾辞。前に漢字/カタカナ2文字以上の「名前部分」が付くものだけ拾う
// (「水族館」単体や「行ったことある商店街」のような助詞・動詞混じりは拾わない)
const FACILITY_RE = /[一-龠ァ-ヴー]{2,8}(?:屋|亭|軒|飯店|食堂|横丁|水族館|美術館|博物館|植物園|動物園|遊園地|商店街|温泉|神社|公園|市場)/g;
const KATAKANA_RE = /[ァ-ヴー]{4,}/g;

/** テキストから固有名詞らしきトークンを取り出す */
export function extractNameTokens(text) {
  const out = new Set();
  const t = String(text ?? '');
  for (const m of t.matchAll(KATAKANA_RE)) {
    if (!KATAKANA_COMMON.has(m[0])) out.add(m[0]);
  }
  for (const m of t.matchAll(FACILITY_RE)) out.add(m[0]);
  for (const name of PROMPT_EXAMPLE_NAMES) if (t.includes(name)) out.add(name);
  return out;
}

/**
 * 返信テキスト群から「根拠テキストに出ていない固有名詞らしき語」を返す。
 * @param {string[]} replyTexts 返信・adviceなど生成された文
 * @param {string} groundingText 会話・プロフィール・文体サンプルなど入力側の全文
 * @returns {string[]} 重複除去済みトークン(出現順)
 */
export function findUngroundedNames(replyTexts, groundingText) {
  const grounding = String(groundingText ?? '');
  const out = [];
  const seen = new Set();
  for (const text of replyTexts || []) {
    for (const tok of extractNameTokens(text)) {
      if (seen.has(tok)) continue;
      if (grounding.includes(tok)) continue;
      seen.add(tok);
      out.push(tok);
    }
  }
  return out;
}
