/**
 * 補助的な捏造候補(完全検出ではない)。人間確認ページで候補として並べるためのもので、停止事由には使わない。
 * @returns {{kind:'known_brand'|'place_store'|'experience_claim'|'known_place'|'self_claim', text:string}[]}
 */
export function findFabricationHints(replyTexts, groundingText) {
  const grounding = String(groundingText ?? '');
  const out = [];
  const seen = new Set();
  const push = (kind, text) => { const k = `${kind}:${text}`; if (!seen.has(k) && !grounding.includes(text)) { seen.add(k); out.push({ kind, text }); } };
  for (const raw of replyTexts || []) {
    const t = String(raw ?? '');
    for (const b of KNOWN_BRANDS) if (t.includes(b)) push('known_brand', b);
    for (const m of t.matchAll(PLACE_STORE_RE)) push('place_store', `${m[1]}の${m[2]}`);
    for (const m of t.matchAll(EXPERIENCE_RE)) push('experience_claim', m[0]);
    for (const p of KNOWN_PLACES) if (t.includes(p)) push('known_place', p);
    for (const m of t.matchAll(SELF_CLAIM_RE)) push('self_claim', m[0]);
  }
  return out;
}

/**
 * 返信テキスト群から「根拠テキストに出ていない固有名詞らしき語」を返す。
 * @param {string[]} replyTexts 返信・adviceなど生成された文
 * @param {string} groundingText 会話・プロフィール・文体サンプルなど入力側の全文
 * @returns {string[]} 重複除去済みトークン(出現順)
 */
export function findUngroundedNames(replyTexts, groundingText) {
  const grounding = String(groundingText ?? '');
  const out = [];
  const seen = new Set();
  for (const text of replyTexts || []) {
    for (const tok of extractNameTokens(text)) {
      if (seen.has(tok)) continue;
      if (grounding.includes(tok)) continue;
      seen.add(tok);
      out.push(tok);
    }
  }
  return out;
}
