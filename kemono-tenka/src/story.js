/** いま語るべき場面を返す(最大 2 つ)。返した場面は、もう語ったものとして盤面に残す */
export function storyDue(s) {
  const out = [], seen = s.story.seen;
  const push = (id, title, lines) => { if (seen.indexOf(id) >= 0 || out.length >= 2) return; seen.push(id); out.push({ id, title, lines }); };
  if (s.phase === 'over') return out;
  if (s.turn === 1) push('prologue', myName(s) + ' の夜', PROLOGUE[CLANS[s.player].key]);
  for (const c of CHAPTERS) if (s.turn >= c.turn && seen.indexOf('ch' + c.turn) < 0) { push('ch' + c.turn, c.title, c.lines(s)); break; }
  for (const t of TRIGGERS) if (seen.indexOf(t.id) < 0 && t.when(s)) push(t.id, t.title, t.lines(s));
  return out;
}

/** 結末。勝ち負けと、約束を守ったか破ったかで 5 つに分かれる */
export function ending(s) {
  const won = s.winner === s.player, w = s.clans[s.winner];
  if (won && s.stats.pactsBroken > 0) return { id: 'cursed', title: '影のない朝', lines: [
    '七つの灯がそろった。鈴が鳴り、東の空が白んでいく。朝だ。',
    '里の者が、おそるおそる戸をあける。あなたを見て、それから、あなたの足もとを見る。',
    '影が、ない。ほどいた髪といっしょに、どこかへ置いてきたのだ。',
    '朝は来た。けれどあなたは、もう朝のものではない。'] };
  if (won && s.stats.pactsMade > 0) return { id: 'dawn', title: '夜明け', lines: [
    '七つの灯がそろった。鈴が鳴り、東の空が白んでいく。朝だ。',
    '結んだ髪は、ほどけなかった。夜の中で守られた約束がひとつあれば、夜は夜でいられなくなる。鈴は、それを言わなかった。',
    '鶏が鳴いた。里の者が、まぶしそうに戸をあける。',
    'あなたは山へ帰る。ふり返ると、七つの里の屋根が、同じ色に光っていた。'] };
  if (won) return { id: 'lord', title: '夜の主', lines: [
    '七つの灯がそろった。鈴が鳴った。……空は、白まない。',
    '鈴は言ったのだ。夜を「従えられる」と。夜は終わらない。あなたのものになっただけだ。',
    '里の者は、あなたの灯に手を合わせる。あなたが灯を吹けば、その里は消える。それが、夜の主ということだ。',
    'だれとも約束を結ばなかった者に、朝は来ない。朝は、ふたり以上でないと、迎えられないものだから。'] };
  if (!s.clans[s.player].alive) return { id: 'swallowed', title: 'のまれる', lines: [
    '最後の灯が消えた。',
    '暗い。けれど、こわくはない。こわいというのは、灯のある者の言葉だ。',
    'だれかが、あなたの名を呼ぼうとして、やめた。舌の上が冷たくなったのだろう。',
    '夜は、あなたの形をひとつ覚えて、また少し深くなった。'] };
  return { id: 'endless', title: '明けない夜', lines: [
    w.name + ' が、夜の主になった。',
    'あなたの灯は取り上げられなかった。ただ、その灯が照らすのは、もうあなたの夜ではない。',
    '里の者は、新しい主のほうを向いて手を合わせる。あなたのほうを向く者は、いない。',
    '鶏は、まだ鳴かない。'] };
}

