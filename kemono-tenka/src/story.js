/*
 * けもの天下 — 夜語り(遊びの進み方に合わせて、物語が書き進む仕組み)
 *
 * 決まった筋書きを順に読ませるのではなく、盤面と、これまでにしたことから、次に語る場面を選ぶ。
 *  - 選んだ家で、始まりの語りが変わる
 *  - 月が変わるたびに 1 つ語る。そのとき優勢か、押されているかで文が変わる
 *  - 初めて里を取った、ほこらを失った、約束を結んだ・破った、百鬼夜行が始まった、などのときに 1 回だけ語る
 *  - 結末は 5 つ。勝ち負けだけでなく、約束を守ったか破ったかで変わる
 *
 * 場面は「いつ語るか(when)」と「何を語るか(lines)」の組。語った場面は盤面(s.story.seen)に残すので、
 * 途中で保存して読み直しても、同じ場面を二度語らない。
 */
import { CAPITAL, WIN_PROVS, CLANS, countOf } from './core.js';

const mine = (s) => countOf(s, s.player);
const top = (s) => { let n = 0; for (const c of s.clans) if (c.alive && c.id !== s.player) n = Math.max(n, countOf(s, c.id)); return n; };
const lead = (s) => mine(s) > top(s);
const behind = (s) => mine(s) <= 2 && top(s) >= 4;
const strongest = (s) => { let w = null; for (const c of s.clans) if (c.alive && c.id !== s.player && (w === null || countOf(s, c.id) > countOf(s, w.id))) w = c; return w; };
const myName = (s) => s.clans[s.player].name;
/** 優勢 / 押されている / 五分 で文を変える */
const by = (s, a, b, c) => (lead(s) ? a : behind(s) ? b : c);

